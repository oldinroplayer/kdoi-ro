#!/usr/bin/env python3
"""Generate server/internal/game/jobs_data.go from the November 2004 eAthena data.

Reads reference/eathena-2004/db/job_db1.txt (weight, HP/SP factors, attack
delay per weapon type), job_db2.txt (job level stat bonuses) and exp.txt (EXP
tables) for the Novice and the six 1st jobs.

Usage: python3 tools/gen_jobs.py
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DB = os.path.join(ROOT, "reference", "eathena-2004", "db")
OUT = os.path.join(ROOT, "server", "internal", "game", "jobs_data.go")

# Rows 0-6 of job_db1/job_db2 are Novice, Swordman, Mage, Archer, Acolyte,
# Merchant, Thief (RO class IDs 0-6).
JOBS = ["Novice", "Swordman", "Mage", "Archer", "Acolyte", "Merchant", "Thief"]
WEAPON_TYPES = 17  # fist, dagger, 1h sword, ... katar (job_db1 columns 4-20)


def data_rows(name):
    rows = []
    with open(os.path.join(DB, name), encoding="latin-1") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("//"):
                continue
            # A few later-job rows have decimals (e.g. 97.5); only rows 0-6 are used.
            rows.append([int(float(v.strip() or 0)) for v in line.split(",")])
    return rows


def go_ints(values):
    return "{" + ", ".join(str(v) for v in values) + "}"


def main():
    db1 = data_rows("job_db1.txt")
    db2 = data_rows("job_db2.txt")
    exp = data_rows("exp.txt")

    # exp.txt columns (see pc_nextbaseexp/pc_nextjobexp in eAthena's pc.c):
    # 0 base EXP for Novice and 1st jobs, 7 Novice job EXP, 8 1st job EXP.
    def column(i):
        out = []
        for row in exp:
            if row[i] == 0:
                break
            out.append(row[i])
        return out

    base = column(0)
    novice_job = column(7)
    first_job = column(8)

    lines = [
        "// Code generated by tools/gen_jobs.py from reference/eathena-2004/db; DO NOT EDIT.",
        "",
        "package game",
        "",
        "// jobTable holds each job's row from job_db1.txt and job_db2.txt.",
        "var jobTable = map[uint16]*JobDef{",
    ]
    for job_id, name in enumerate(JOBS):
        r1 = db1[job_id]
        weight, hp_factor, hp_mul, sp_factor = r1[0], r1[1], r1[2], r1[3]
        aspd = r1[4:4 + WEAPON_TYPES]
        bonus = db2[job_id][:50]
        lines += [
            f"\t{job_id}: {{",
            f'\t\tID: {job_id}, Name: "{name}",',
            f"\t\tBaseWeight: {weight // 10}, HPFactor: {hp_factor}, HPMultiplier: {hp_mul}, SPFactor: {sp_factor},",
            f"\t\tAttackDelay: [WeaponTypes]int{go_ints(aspd)},",
            f"\t\tJobBonus: []int{go_ints(bonus)},",
            "\t},",
        ]
    lines += [
        "}",
        "",
        "// baseExpTable[lv-1] is the base EXP from lv to lv+1 (Novice and 1st jobs).",
        f"var baseExpTable = []int{go_ints(base)}",
        "",
        "// noviceJobExp[lv-1] is the Novice job EXP from lv to lv+1.",
        f"var noviceJobExp = []int{go_ints(novice_job)}",
        "",
        "// firstJobExp[lv-1] is the 1st-job job EXP from lv to lv+1.",
        f"var firstJobExp = []int{go_ints(first_job)}",
        "",
    ]
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: {len(JOBS)} jobs, base EXP to Lv {len(base) + 1}, "
          f"novice job to {len(novice_job) + 1}, 1st job to {len(first_job) + 1}")


if __name__ == "__main__":
    main()
