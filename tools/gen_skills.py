#!/usr/bin/env python3
"""Generate server/internal/game/skills_data.go from the November 2004 eAthena data.

Reads reference/eathena-2004/db/skill_db.txt (range, target, element, hits,
knockback), skill_require_db.txt (SP and zeny per level, allowed weapons),
skill_cast_db.txt (cast time, delay, buff duration per level) and
skill_tree.txt (which job learns it, and its prerequisites) for the skills
KDoiRo implements. What each skill *does* is hand-written in Go.

Usage: python3 tools/gen_skills.py
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DB = os.path.join(ROOT, "reference", "eathena-2004", "db")
OUT = os.path.join(ROOT, "server", "internal", "game", "skills_data.go")

# The 1st-job skills KDoiRo implements, by ID.
SKILLS = {
    2: "SM_SWORD", 4: "SM_RECOVERY", 5: "SM_BASH", 7: "SM_MAGNUM",
    9: "MG_SRECOVERY", 14: "MG_COLDBOLT", 19: "MG_FIREBOLT", 20: "MG_LIGHTNINGBOLT",
    43: "AC_OWL", 44: "AC_VULTURE", 46: "AC_DOUBLE",
    22: "AL_DP", 28: "AL_HEAL", 29: "AL_INCAGI", 34: "AL_BLESSING",
    36: "MC_INCCARRY", 37: "MC_DISCOUNT", 38: "MC_OVERCHARGE", 42: "MC_MAMMONITE",
    48: "TF_DOUBLE", 49: "TF_MISS", 52: "TF_POISON",
}

# skill_db "inf" -> SkillTarget.
TARGETS = {0: "TargetPassive", 1: "TargetEnemy", 2: "TargetGround", 4: "TargetSelf", 16: "TargetFriend"}


def rows(name):
    """Data rows keyed by skill ID. The files mix CRLF and stray Shift-JIS bytes."""
    out = {}
    with open(os.path.join(DB, name), "rb") as f:
        for raw in f.read().split(b"\n"):
            line = raw.split(b"//")[0].strip().decode("latin-1")
            if not line or not line[0].isdigit():
                continue
            fields = [v.strip() for v in line.split(",")]
            out.setdefault(int(fields[0]), fields)
    return out


def levels(field, max_level):
    """'8:8:15' -> per-level list, padded with the last value."""
    values = [int(float(v)) for v in field.split(":") if v != ""] or [0]
    return [values[min(i, len(values) - 1)] for i in range(max_level)]


def go_ints(values):
    return "[]int{" + ", ".join(str(v) for v in values) + "}"


def main():
    skill_db = rows("skill_db.txt")
    require = rows("skill_require_db.txt")
    cast = rows("skill_cast_db.txt")

    # skill_tree.txt rows are job,skill,maxlv,(req id,req lv) x5 and can repeat
    # skills across jobs, so read them separately.
    tree = {}
    with open(os.path.join(DB, "skill_tree.txt"), "rb") as f:
        for raw in f.read().split(b"\n"):
            line = raw.split(b"//")[0].strip().decode("latin-1")
            if not line or not line[0].isdigit():
                continue
            try:
                v = [int(x) for x in line.split(",") if x.strip() != ""]
            except ValueError:
                continue  # a few later-job rows are malformed (e.g. "22.334")
            job, skill = v[0], v[1]
            if skill in SKILLS and 1 <= job <= 6 and skill not in tree:
                reqs = [(v[i], v[i + 1]) for i in range(3, len(v) - 1, 2) if v[i] != 0]
                tree[skill] = (job, reqs)

    lines = [
        "// Code generated by tools/gen_skills.py from reference/eathena-2004/db; DO NOT EDIT.",
        "",
        "package game",
        "",
        "// firstJobSkills are the 1st-job skills, with numbers from the 2004 skill DBs.",
        "var firstJobSkills = []*SkillDef{",
    ]
    for sid in sorted(SKILLS):
        name = SKILLS[sid]
        d = skill_db[sid]
        max_level = int(d[6])
        job, reqs = tree[sid]
        r = require.get(sid)
        c = cast.get(sid)
        sp = levels(r[3], max_level) if r else [0] * max_level
        zeny = levels(r[6], max_level) if r else [0] * max_level
        weapons = sorted({int(w) for w in r[7].split(":") if w != ""}) if r and r[7] not in ("", "99") else []
        cast_time = levels(c[1], max_level) if c else [0] * max_level
        delay = levels(c[2], max_level) if c else [0] * max_level
        duration = levels(c[3], max_level) if c else [0] * max_level
        fields = [
            f"ID: {sid}, Name: \"{name}\", Job: {job}, MaxLevel: {max_level},",
            f"Target: {TARGETS[int(d[3])]}, Range: {int(d[1])}, Element: {int(d[4])}, Knockback: {int(d[13])},",
            f"Hits: {go_ints(levels(d[7], max_level))},",
        ]
        if any(sp):
            fields.append(f"SP: {go_ints(sp)},")
        if any(zeny):
            fields.append(f"Zeny: {go_ints(zeny)},")
        if any(cast_time):
            fields.append(f"CastTime: {go_ints(cast_time)},")
        if any(delay):
            fields.append(f"Delays: {go_ints(delay)},")
        if any(duration):
            fields.append(f"Duration: {go_ints(duration)},")
        if weapons and weapons != list(range(len(weapons))):
            fields.append(f"Weapons: {go_ints(weapons)},")
        if reqs:
            fields.append("Requires: []SkillReq{" + ", ".join(f"{{ID: {i}, Level: {lv}}}" for i, lv in reqs) + "},")
        lines.append("\t{")
        lines += ["\t\t" + f for f in fields]
        lines.append("\t},")
    lines += ["}", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: {len(SKILLS)} skills")


if __name__ == "__main__":
    main()
